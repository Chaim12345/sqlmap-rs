//! WAF/IPS identification (port of sqlmap `lib/core/waf.py` + the `waf/*.py`
//! script subset): fire one attack-laden request at the target and match the
//! response - status line, headers, body - against a signature table of
//! well-known web application firewalls.

use sqlmap_core::config::Config;
use sqlmap_http::client::{Client, RequestSpec};

/// Attack payload riding in a throwaway parameter, trimmed from sqlmap's
/// IPS_WAF_CHECK_PAYLOAD (`lib/core/settings.py`): SQLi, XSS and path
/// traversal in one string so any rule-based WAF trips on it.
const ATTACK: &str = "1 AND 1=1 UNION ALL SELECT 1,2,3,table_name FROM information_schema.tables \
                      WHERE 2>1-- <script>alert(1)</script> ../../../etc/passwd";

/// One WAF signature: the WAF is identified when ANY of its markers hits the
/// attack response. Markers are the stable strings the real products emit
/// (the same ones sqlmap's waf scripts match on).
struct Signature {
    name: &'static str,
    /// Header values containing any of these (case-insensitive).
    header_contains: &'static [&'static str],
    /// Body containing any of these (case-insensitive).
    body_contains: &'static [&'static str],
}

const SIGNATURES: &[Signature] = &[
    Signature {
        name: "Cloudflare",
        header_contains: &["cloudflare"],
        body_contains: &["attention required! | cloudflare", "cloudflare-nginx"],
    },
    Signature {
        name: "ModSecurity",
        header_contains: &["mod_security"],
        body_contains: &["mod_security"],
    },
    Signature {
        name: "WebKnight",
        header_contains: &[],
        body_contains: &["webknight"],
    },
    Signature {
        name: "F5 BIG-IP ASM",
        header_contains: &["big-ip", "f5"],
        body_contains: &["the requested url was rejected"],
    },
    Signature {
        name: "Sucuri",
        header_contains: &["x-sucuri"],
        body_contains: &["sucuri website firewall", "access denied - sucuri"],
    },
    Signature {
        name: "Incapsula",
        header_contains: &["incap_ses", "_incapsula_"],
        body_contains: &["incapsula incident id"],
    },
    Signature {
        name: "Wordfence",
        header_contains: &[],
        body_contains: &["generated by wordfence", "wordfence"],
    },
];

/// Match one response against the signature table, in table order.
fn match_signatures(headers: &[(String, String)], body: &str) -> Option<&'static str> {
    let body_lc = body.to_ascii_lowercase();
    let header_lc: Vec<String> = headers
        .iter()
        .map(|(k, v)| format!("{}: {}", k.to_ascii_lowercase(), v.to_ascii_lowercase()))
        .collect();
    for sig in SIGNATURES {
        if sig
            .header_contains
            .iter()
            .any(|m| header_lc.iter().any(|h| h.contains(m)))
            || sig.body_contains.iter().any(|m| body_lc.contains(m))
        {
            return Some(sig.name);
        }
    }
    None
}

/// Identify a WAF/IPS in front of the target (sqlmap --identify-waf):
/// request the target once with an attack-laden throwaway parameter and
/// match the response against the signature table. Returns the identified
/// product names plus human-readable log lines.
pub fn identify(client: &Client, conf: &Config) -> (Vec<String>, Vec<String>) {
    let mut log = Vec::new();
    let sep = if conf.target_url.contains('?') { '&' } else { '?' };
    let probe = format!(
        "{}{sep}sqlmaprs-waf-check={}",
        conf.target_url,
        sqlmap_http::params::encode(ATTACK)
    );
    let resp = client.request(&RequestSpec {
        url: probe,
        method: "GET".into(),
        body: None,
        headers: Vec::new(),
        cookie: conf.cookie.clone(),
    });
    let mut found = Vec::new();
    match resp {
        Ok(resp) => {
            if let Some(name) = match_signatures(&resp.headers, &resp.body) {
                log.push(format!(
                    "WAF/IPS identified: {name} (attack probe answered with status {})",
                    resp.status
                ));
                found.push(name.to_string());
            } else {
                log.push(format!(
                    "no WAF/IPS identified (attack probe answered with status {})",
                    resp.status
                ));
            }
        }
        Err(e) => log.push(format!("WAF identification probe failed: {e}")),
    }
    (found, log)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn headers(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    #[test]
    fn matches_known_wafs() {
        assert_eq!(
            match_signatures(&[], "<title>406</title>This error was generated by Mod_Security."),
            Some("ModSecurity")
        );
        assert_eq!(
            match_signatures(&headers(&[("Server", "cloudflare")]), "error"),
            Some("Cloudflare")
        );
        assert_eq!(
            match_signatures(&[], "WebKnight Application Firewall Alert"),
            Some("WebKnight")
        );
        assert_eq!(
            match_signatures(&[], "The requested URL was rejected. Please consult."),
            Some("F5 BIG-IP ASM")
        );
        assert_eq!(
            match_signatures(&[], "Access Denied - Sucuri Website Firewall"),
            Some("Sucuri")
        );
        assert_eq!(
            match_signatures(&headers(&[("Set-Cookie", "incap_ses_1=abc")]), "x"),
            Some("Incapsula")
        );
        assert_eq!(
            match_signatures(&[], "Generated by Wordfence at"),
            Some("Wordfence")
        );
    }

    #[test]
    fn no_match_on_plain_page() {
        assert_eq!(
            match_signatures(&headers(&[("Server", "Apache/2.4")]), "<html><body>ok</body></html>"),
            None
        );
    }
}
